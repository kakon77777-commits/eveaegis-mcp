@dataclass(slots=True)
class ClassifiedFile:
    path: str
    component_class: ComponentClass
    size: int
    reason: str
    dimension: ContributionDimension | None = None


@dataclass(slots=True)
class ComponentSummary:
    """Aggregated §9.3 view of a repository tree.

    ``effective_*`` is the denominator §8.2 calls "目前有效內容": everything that a
    human plausibly authored or curated, with packages, build output and binaries
    removed.
    """

    files: list[ClassifiedFile] = field(default_factory=list)
    total_files: int = 0
    total_bytes: int = 0
    effective_files: int = 0
    effective_bytes: int = 0
    files_by_class: dict[ComponentClass, int] = field(default_factory=dict)
    bytes_by_class: dict[ComponentClass, int] = field(default_factory=dict)
    files_by_dimension: dict[ContributionDimension, int] = field(default_factory=dict)
    bytes_by_dimension: dict[ContributionDimension, int] = field(default_factory=dict)
    excluded_roots: list[str] = field(default_factory=list)
    dependency_manifests: list[str] = field(default_factory=list)
    lock_files: list[str] = field(default_factory=list)
    license_files: list[str] = field(default_factory=list)
    attribution_files: list[str] = field(default_factory=list)
    embedded_license_files: list[str] = field(default_factory=list)
    submodule_declared: bool = False

    # -- ratios ---------------------------------------------------------

    def share_of_files(self, component_class: ComponentClass) -> float:
        return self.files_by_class.get(component_class, 0) / self.total_files if self.total_files else 0.0

    def share_of_bytes(self, component_class: ComponentClass) -> float:
        return self.bytes_by_class.get(component_class, 0) / self.total_bytes if self.total_bytes else 0.0

    @property
    def effective_file_ratio(self) -> float:
        """How much of the tree survives the §9.2 exclusions, by file count."""
        return self.effective_files / self.total_files if self.total_files else 0.0

    @property
    def vendored_files(self) -> int:
        return self.files_by_class.get(ComponentClass.VENDORED, 0) + self.files_by_class.get(
            ComponentClass.VENDORED_MODIFIED, 0
        )

    @property
    def dependency_files(self) -> int:
        return self.files_by_class.get(ComponentClass.DEPENDENCY, 0)

    @property
    def generated_files(self) -> int:
        return self.files_by_class.get(ComponentClass.GENERATED, 0)

    def effective_paths(self) -> list[str]:
        return [f.path for f in self.files if f.component_class not in NON_EFFECTIVE_CLASSES]

    # -- persistence ----------------------------------------------------

    def to_profiles(self, *, max_rows: int = 200) -> list[ComponentProfile]:
        """Roll per-file classifications up into storable :class:`ComponentProfile` rows.

        Per-file rows would be tens of thousands for a vendored repository, so files
        are grouped by (component root, class). The grouping key is the excluded
        directory when there is one, otherwise the top-level path segment — which is
        exactly the granularity a human reviewer reasons about.
        """
        buckets: dict[tuple[str, ComponentClass], dict[str, Any]] = {}
        for item in self.files:
            root = _component_root(item.path, item.component_class)
            key = (root, item.component_class)
            bucket = buckets.setdefault(key, {"bytes": 0, "files": 0, "reason": item.reason})
            bucket["bytes"] += item.size
            bucket["files"] += 1
        rows = [
            ComponentProfile(
                path=path,
                component_class=component_class,
                bytes=data["bytes"],
                files=data["files"],
                reason=data["reason"],
            )
            for (path, component_class), data in buckets.items()
        ]
        rows.sort(key=lambda r: (-r.files, r.path))
        return rows[:max_rows]


