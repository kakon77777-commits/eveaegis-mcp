def _component_root(path: str, component_class: ComponentClass) -> str:
    parts = path.split("/")
    if component_class in NON_EFFECTIVE_CLASSES:
        # Report the deepest recognised exclusion root, e.g. "web/node_modules".
        for index, part in enumerate(parts[:-1]):
            lowered = part.lower()
            if lowered in DEPENDENCY_DIRS or lowered in VENDORED_DIRS or lowered in GENERATED_DIRS:
                return "/".join(parts[: index + 1])
    return parts[0] if len(parts) > 1 else "."


def _normalize_entry(entry: Any) -> tuple[str, int, str] | None:
    """Accept GitHub tree entries, ``(path, size)`` pairs, or bare paths."""
    if isinstance(entry, Mapping):
        if entry.get("type") not in (None, "blob"):
            return None  # trees and commits (submodule gitlinks) carry no content
        path = str(entry.get("path") or "")
        return (path, int(entry.get("size") or 0), str(entry.get("mode") or "")) if path else None
    if isinstance(entry, (tuple, list)) and len(entry) >= 2:
        return str(entry[0]), int(entry[1]), ""
    if isinstance(entry, str):
        return entry, 0, ""
    return None


def _dimension_for(path: str) -> ContributionDimension:
    """Map a path onto a §8.3 contribution dimension. Heuristic, and only used to
    describe *where* work sits — never to decide whether work happened."""
    lowered = path.lower()
    parts = lowered.split("/")
    name = parts[-1]
    _, ext = posixpath.splitext(name)

    if any(part in TEST_DIR_NAMES for part in parts[:-1]) or name.startswith("test_") or "_test." in name or ".test." in name or ".spec." in name:
        return ContributionDimension.TESTS
    if any(part in DEPLOY_DIR_NAMES for part in parts[:-1]) or name in {"dockerfile", "makefile", "procfile", "wrangler.toml", "vercel.json", "netlify.toml"}:
        return ContributionDimension.DEPLOYMENT
    if any(part in DOC_DIR_NAMES for part in parts[:-1]) or ext in DOC_EXTENSIONS:
        return ContributionDimension.DOCUMENTATION
    if any(part in RESEARCH_DIR_NAMES for part in parts[:-1]) or ext == ".ipynb":
        return ContributionDimension.RESEARCH
    if ext in ASSET_EXTENSIONS:
        return ContributionDimension.ASSETS
    if any(part in UI_DIR_NAMES for part in parts[:-1]) or ext in {".css", ".scss", ".less", ".html", ".vue", ".svelte", ".jsx", ".tsx"}:
        return ContributionDimension.UI_UX
    if any(part in DATA_DIR_NAMES for part in parts[:-1]) or ext in {".sql", ".prisma", ".graphql", ".proto"}:
        return ContributionDimension.DATA_MODEL
    if ext in {".json", ".yaml", ".yml", ".toml", ".csv", ".xml"}:
        return ContributionDimension.CONTENT
    return ContributionDimension.CODE


def _classify_one(
    path: str,
    size: int,
    mode: str,
    *,
    dependency_dirs: frozenset[str],
    vendored_dirs: frozenset[str],
    generated_dirs: frozenset[str],
    default_class: ComponentClass,
) -> tuple[ComponentClass, str]:
    parts = path.split("/")
    name = parts[-1].lower()
    directories = [p.lower() for p in parts[:-1]]

    # §9.2 exclusions win over everything else: a minified bundle inside
    # node_modules is a dependency, not "generated local work".
    for directory in directories:
        if directory in dependency_dirs:
            return ComponentClass.DEPENDENCY, f"under dependency directory '{directory}/' (§9.2)"
    for directory in directories:
        if directory in vendored_dirs:
            return ComponentClass.VENDORED, f"under vendored directory '{directory}/' (§9.2)"
    for index, directory in enumerate(directories):
        if directory in generated_dirs or "/".join(directories[: index + 1]) in generated_dirs:
            return ComponentClass.GENERATED, f"under build/generated directory '{directory}/' (§9.2)"

    if name in GENERATED_FILES:
        return ComponentClass.GENERATED, "lock file — written by a package manager"
    if any(name.endswith(suffix) for suffix in GENERATED_SUFFIXES):
        return ComponentClass.GENERATED, "file name marks compiled or generated output"

    _, ext = posixpath.splitext(name)
    if ext in BINARY_EXTENSIONS:
        return ComponentClass.BINARY, f"binary extension '{ext}'"
    if ext in ASSET_EXTENSIONS:
        return ComponentClass.ASSET, f"asset extension '{ext}'"
    if mode == "160000":
        return ComponentClass.VENDORED, "git submodule gitlink"

    return default_class, "no exclusion matched"


def classify_paths(
    entries: Iterable[Any],
    *,
    config: AnalysisConfig | None = None,
    default_class: ComponentClass = ComponentClass.UNKNOWN,
    extra_excluded_dirs: Iterable[str] = (),
) -> ComponentSummary:
    """Classify every path in a repository tree (§9.3).

    ``entries`` accepts GitHub ``git/trees`` items, ``(path, size)`` pairs, or bare
    path strings. ``default_class`` stays :data:`ComponentClass.UNKNOWN` unless the
    caller has *positively established* there is no upstream — see the module
    docstring on why the default is not ``ORIGINAL``.
    """
    cfg = config or AnalysisConfig()
    configured = {d.strip("/").lower() for d in cfg.excluded_dirs} | {
        d.strip("/").lower() for d in extra_excluded_dirs
    }
    # The configured exclusion list is a flat set; split it back into the three
    # semantically different families so a `vendor/` hit is not reported as a
    # dependency (§9.1 keeps these strictly apart).
    dependency_dirs = DEPENDENCY_DIRS | (configured & DEPENDENCY_DIRS)
    vendored_dirs = VENDORED_DIRS | (configured & VENDORED_DIRS)
    generated_dirs = GENERATED_DIRS | (configured - DEPENDENCY_DIRS - VENDORED_DIRS)

    summary = ComponentSummary()
    excluded_roots: set[str] = set()

    for raw in entries:
        normalized = _normalize_entry(raw)
        if normalized is None:
            continue
        path, size, mode = normalized
        component_class, reason = _classify_one(
            path,
            size,
            mode,
            dependency_dirs=dependency_dirs,
            vendored_dirs=vendored_dirs,
            generated_dirs=generated_dirs,
            default_class=default_class,
        )
        dimension = _dimension_for(path) if component_class not in NON_EFFECTIVE_CLASSES else None
        summary.files.append(ClassifiedFile(path, component_class, size, reason, dimension))

        summary.total_files += 1
        summary.total_bytes += size
        summary.files_by_class[component_class] = summary.files_by_class.get(component_class, 0) + 1
        summary.bytes_by_class[component_class] = summary.bytes_by_class.get(component_class, 0) + size

        if component_class in NON_EFFECTIVE_CLASSES:
            excluded_roots.add(_component_root(path, component_class))
        else:
            summary.effective_files += 1
            summary.effective_bytes += size
            if dimension is not None:
                summary.files_by_dimension[dimension] = summary.files_by_dimension.get(dimension, 0) + 1
                summary.bytes_by_dimension[dimension] = summary.bytes_by_dimension.get(dimension, 0) + size

        _record_special_file(summary, path, component_class)

    summary.excluded_roots = sorted(excluded_roots)
    return summary


def _record_special_file(summary: ComponentSummary, path: str, component_class: ComponentClass) -> None:
    """Note manifests, licences and attribution files wherever they appear.

    Deliberately runs for excluded paths too: a ``LICENSE`` sitting inside
    ``vendor/`` is the single most important licence signal in §10, and dropping it
    with the rest of the vendored tree would hide a copyleft trigger.
    """
    name = path.split("/")[-1].lower()
    stem = posixpath.splitext(name)[0]
    directories = [p.lower() for p in path.split("/")[:-1]]
    # "Inside an excluded directory", not "has a non-effective class": a lock file
    # at the repository root is GENERATED but its manifest neighbourhood still
    # matters, whereas a manifest inside node_modules describes someone else's package.
    inside_excluded = any(
        d in DEPENDENCY_DIRS or d in VENDORED_DIRS or d in GENERATED_DIRS for d in directories
    )

    if name in DEPENDENCY_MANIFESTS and not inside_excluded:
        summary.dependency_manifests.append(path)
    if name in LOCK_FILES and not inside_excluded:
        summary.lock_files.append(path)
    if stem in {"license", "licence", "copying", "copyright", "unlicense"}:
        if inside_excluded or "/" in path:
            summary.embedded_license_files.append(path)
        else:
            summary.license_files.append(path)
    if stem in {"notice", "authors", "contributors", "credits", "acknowledgements", "acknowledgments", "third_party_notices", "third-party-notices"}:
        summary.attribution_files.append(path)
    if name == ".gitmodules":
        summary.submodule_declared = True
