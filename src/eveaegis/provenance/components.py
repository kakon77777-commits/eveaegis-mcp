"""Component classification (§9 Dependency ≠ Upstream Source ≠ Vendored Code).

This module runs *before* any similarity is computed, and it is the single most
load-bearing correctness property in the provenance engine. A repository that
vendors 40 000 ``node_modules`` files is not "mostly upstream" — those files were
never authored by anyone in the portfolio and were never authored by the upstream
either. Letting them into a denominator produces exactly the confident, wrong
answer §29 forbids ("依賴不被誤判為上游來源").

So classification is structural and evidence-based, and the default for content we
cannot place is :data:`ComponentClass.UNKNOWN`, never ``ORIGINAL``. The engine only
promotes UNKNOWN to ORIGINAL once it has established that no upstream exists
(axiom 4: absence of a known source is not proof of authorship).
"""

